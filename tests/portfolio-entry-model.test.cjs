test('VIX term ranks use prior paired date, integer ratio ties and a bounded window', () => {
  const context = { series: dates(1000).map((day, i) => [day, i % 2 ? '.9' : '.3', i % 2 ? '.3' : '.1']) };
  const { rows } = E.buildFeatures({ ...market(), context });
  assert.equal(rows[126].VIX, null); assert.equal(rows[127].VIX, .5);
  assert.equal(rows[127].sourceDates.VIX.observationDay, dateAt(126));
  assert.equal(rows[1000].VIX, .5); assert.equal(rows[1000].priorCounts.VIX, 756);
  assert.equal(rows[1007].VIX, null);
  assert.equal(rows[1007].missingReasons.VIX, 'stale_vix_close');
});

test('missing or invalid option source suppresses only methods that require it', () => {
  for (const context of [undefined, { series: [[dateAt(1), 20.001, 22]] }]) {
    const row = E.buildFeatures({ ...market(400), context }).rows.at(-1), out = E.scores(row).methods;
    assert.equal(out.entry_option.available, false); assert.equal(out.entry_composite.available, false);
    assert.equal(out.entry_volatility.available, true); assert.equal(out.entry_breadth.available, true);
    assert.ok(out.entry_option.missingReasons.some(r => r.field === 'VIX'));
  }
});

test('three fixed nonlinear scores and missingness have no probability or action labels', () => {
  const row = { date: '2020-01-01', D_mix: .4, D_21: .3, VIX: .75, VOL: .5, BREADTH: 1 };
  const s = E.scores(row).methods;
  close(s.entry_option.signal0to1, .6); close(s.entry_volatility.signal0to1, .3);
  close(s.entry_breadth.signal0to1, .3 + (2 / 3) * .7);
  close(s.entry_composite.signal0to1, (.6 + .3 + .3 + (2 / 3) * .7) / 3);
  close(s.entry_option.score0to100, 60);
  assert.equal(E.scores({ ...row, VIX: null }).methods.entry_composite.signal0to1, null);
  assert.equal(E.scores({ ...row, VOL: NaN }).methods.entry_volatility.signal0to1, null);
  assert.equal(Object.hasOwn(s.entry_option, 'recommendation'), false);
});

test('future source changes, truncation and appended prices cannot rewrite feature prefixes', () => {
  const input = market(700), context = { series: dates(700).map((d, i) => [d, 10 + (i % 41) / 100, 20 + (i % 23) / 100]) };
  const all = E.buildFeatures({ ...input, context }).rows;
  const prefix = E.buildFeatures({ dates: input.dates.slice(0, 450), prices: input.prices.slice(0, 450), weights: input.weights,
    context: { series: context.series.slice(0, 450) } }).rows;
  assert.deepEqual(all.slice(0, 450), prefix);
  const changed = E.buildFeatures({ ...input, prices: input.prices.map((p, i) => i >= 450 ? p.map(v => v * 7) : p),
    context: { series: context.series.map((r, i) => i >= 450 ? [r[0], 99, 11] : r) } }).rows;
  assert.deepEqual(changed.slice(0, 450), prefix);
});

test('high-score releases use the same initial principal, cannot repeat a tranche, finish in month 12', () => {
  const p = E.plan(months, scoredRows(.99), 'entry_volatility', 100);
  assert.equal(p.orders.length, 2); close(p.orders[0].amount, 99); close(p.orders[1].amount, 1);
  assert.equal(p.orders[1].day, months[11].day); close(p.released, 100); close(p.remaining, 0);
  assert.equal(p.coverage.plannedMonths, 12); assert.equal(p.coverage.availableMonths, 12);
  assert.ok(p.orders.every(r => r.signalDate < r.day && r.amount >= 0));
});

test('missing initial common close or scores retain the twelve-month minimum schedule', () => {
  const allMissing = E.plan([{ ...months[0], signalDate: null }, ...months.slice(1)], {}, 'entry_composite', 120);
  assert.equal(allMissing.orders.length, 12); allMissing.orders.forEach(r => close(r.amount, 10));
  close(allMissing.released, 120); assert.equal(allMissing.coverage.initialAvailable, false);
  assert.equal(allMissing.decisions[0].missingReasons[0].code, 'missing_signal_close');
  const partial = E.plan(months.slice(0, 6), {}, 'entry_composite', 120);
  close(partial.released, 60); close(partial.remaining, 60);
  assert.equal(E.plan(months, {}, 'entry_option', 0).orders.length, 0);
});

test('future scores do not alter already placed orders and feature rows cannot be backdated', () => {
  const original = scoredRows(.2), changed = structuredClone(original);
  for (const m of months.slice(6)) changed[m.signalDate].D_21 = 1;
  const a = E.plan(months, original, 'entry_volatility', 100).orders.filter(x => x.day <= months[5].day);
  const b = E.plan(months, changed, 'entry_volatility', 100).orders.filter(x => x.day <= months[5].day);
  assert.deepEqual(a, b);
  assert.throws(() => E.plan([{ day: '2020-01-02', signalDate: '2020-01-02' }], original, 'entry_option', 100));
  assert.throws(() => E.plan(months, { ...original, [months[0].signalDate]: { ...original[months[0].signalDate], date: '2020-01-03' } }, 'entry_option', 100));
  assert.throws(() => E.plan(months, original, 'unknown', 100));
});

test('invalid or reordered price observations are rejected rather than filled', () => {
  const input = market(10);
  assert.throws(() => E.buildFeatures({ ...input, dates: [input.dates[1], ...input.dates.slice(1)] }));
  assert.throws(() => E.buildFeatures({ ...input, prices: [[NaN, 2], ...input.prices.slice(1)] }));
  assert.throws(() => E.buildFeatures({ ...input, weights: [.8, .3] }));
});

