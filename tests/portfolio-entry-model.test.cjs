const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const E = require('../assets/portfolio-entry-model.js');

const dateAt = i => new Date(Date.UTC(2000, 0, 1 + i)).toISOString().slice(0, 10);
const dates = n => Array.from({ length: n }, (_, i) => dateAt(i));
const config = { currency: 'CNY', positions: [{ id: 'us:USD', weight: 30 }, { id: 'us:TQQQ', weight: 30 }] };
function market(n = 1100) {
  return { dates: dates(n), prices: Array.from({ length: n }, (_, i) => [100 + (i % 43) * 3 + Math.floor(i / 43) * 2 + (i % 7),
    90 + (i % 67) * 2 + Math.floor(i / 67) * 3 + (i % 11)]), weights: [.3, .3] };
}
const close = (a, b, tolerance = 1e-12) => assert.ok(Math.abs(a - b) <= tolerance, `${a} != ${b}`);
const months = Array.from({ length: 14 }, (_, i) => {
  const day = new Date(Date.UTC(2020, i, 2)).toISOString().slice(0, 10);
  const signalDate = new Date(Date.UTC(2020, i, 1)).toISOString().slice(0, 10);
  return { day, signalDate };
});
const scoredRows = value => Object.fromEntries(months.map(m => [m.signalDate,
  { date: m.signalDate, D_mix: value, D_21: value, VIX: .5, VOL: .5, BREADTH: .5 }]));

test('works as a browser global without CommonJS or network dependencies', () => {
  const context = {}; vm.createContext(context);
  vm.runInContext(fs.readFileSync(require.resolve('../assets/portfolio-entry-model.js'), 'utf8'), context);
  assert.equal(typeof context.ChanghengPortfolioEntry.plan, 'function');
  assert.equal(context.ChanghengPortfolioEntry.metadata.validatedForecast, false);
});

test('supported scope checks actual IDs, weights and reporting currency', () => {
  assert.equal(E.supports(config).supported, true);
  assert.equal(E.supports({ ...config, positions: [...config.positions].reverse() }).supported, true);
  for (const other of [undefined, { ...config, currency: 'USD' }, { ...config, positions: [{ id: 'us:USD', weight: 30 }, { id: 'us:QQQ', weight: 30 }] },
    { ...config, positions: [{ id: 'us:USD', weight: 31 }, { id: 'us:TQQQ', weight: 29 }] },
    { ...config, positions: [{ id: 'us:USD', weight: 30 }, { id: 'us:USD', weight: 30 }] }]) {
    assert.equal(E.supports(other).supported, false);
    assert.equal(E.supports(other).reasonCode, 'unsupported_portfolio');
  }
});

test('research scope requires no rebalancing and net prices without limiting principal scale or transaction charges', () => {
  for (const rebalance of ['month', 'quarter', 'year']) {
    const scope = E.supports({ ...config, rebalance });
    assert.equal(scope.supported, false); assert.equal(scope.reasonCode, 'unsupported_rebalance');
    const assessed = E.scores({ date: '2020-01-01', D_mix: .5, D_21: .5, VIX: .5, VOL: .5, BREADTH: .5, scope });
    for (const method of Object.values(assessed.methods)) {
      assert.equal(method.available, false); assert.equal(method.missingReasons[0].code, 'unsupported_rebalance');
    }
  }
  assert.equal(E.supports({ ...config, feeBasis: 'gross_estimate' }).reasonCode, 'unsupported_fee_basis');
  assert.equal(E.supports({ ...config, rebalance: 'none', feeBasis: 'net', initial: 500000, transactionFee: .1 }).supported, true);
});

test('a supplied unsupported scope suppresses all methods, not generic feature calculation', () => {
  const input = market(400);
  const out = E.buildFeatures({ ...input, context: { config: { ...config, currency: 'USD' } } });
  assert.notEqual(out.rows.at(-1).D_21, null);
  for (const method of Object.values(E.scores(out.rows.at(-1)).methods)) {
    assert.equal(method.signal0to1, null);
    assert.equal(method.missingReasons[0].code, 'unsupported_portfolio');
  }
});

